namespace MAGUS.GameSystem.Magic.ElementalMagic;

/// <summary>
/// The four para-elements (Paraelemek), each the manifest effect of one primal element:
/// Fire→Heat, Water→Frost, Earth→Darkness, Air→Light.
/// Source: M.A.G.U.S. Első Törvénykönyv, p. 292.
/// </summary>
public enum ParaElementType
{
    Heat,       // Elemi Hő (Őstűz hatása)
    Frost,      // Elemi Fagy (Ősvíz hatása)
    Light,      // Elemi Fény (Őslég hatása)
    Darkness    // Elemi Sötét (Ősföld hatása)
}
